import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export function generate(contract) {
  const schemas = contract.components.schemas;
  const type = schema => {
    if (schema.$ref) {
      const name = schema.$ref.replace('#/components/schemas/', '');
      assert.ok(schemas[name], `unknown schema ${name}`);
      return name;
    }
    if (!schema.type) { assert.equal(Object.keys(schema).length, 0, 'unsupported schema'); return 'serde_json::Value'; }
    switch (schema.type) {
      case 'string': return 'String';
      case 'boolean': return 'bool';
      case 'integer': return 'i64';
      case 'number': return 'f64';
      case 'array': return `Vec<${type(schema.items)}>`;
      case 'object':
        assert.ok(!schema.properties, 'inline object needs a named schema');
        return schema.additionalProperties && typeof schema.additionalProperties === 'object'
          ? `std::collections::BTreeMap<String, ${type(schema.additionalProperties)}>` : 'serde_json::Value';
      default: throw new Error(`unsupported schema type ${schema.type}`);
    }
  };
  const declarations = Object.entries(schemas).map(([name, schema]) => {
    if (schema.type !== 'object' || !schema.properties) return `pub type ${name} = ${type(schema)};`;
    const required = new Set(schema.required);
    const fields = Object.entries(schema.properties).map(([field, shape]) => {
      assert.match(field, /^[a-z][a-z0-9_]*$/);
      const optional = !required.has(field);
      return `${optional ? '    #[serde(default, skip_serializing_if = "Option::is_none")]\n' : ''}    pub ${['type', 'ref'].includes(field) ? `r#${field}` : field}: ${optional ? `Option<${type(shape)}>` : type(shape)},`;
    });
    return `#[derive(\n    Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema,\n)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n${fields.join('\n')}\n}`;
  });
  return `// Generated by tools/brain-contract.mjs from contracts/brain.openapi.json.\n\n${declarations.join('\n\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = new URL('../contracts/brain.openapi.json', import.meta.url);
  const target = new URL('../crates/aex-server/src/brain_contract.rs', import.meta.url);
  const generated = generate(JSON.parse(await readFile(source, 'utf8')));
  if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), generated, 'regenerate Brain DTOs');
  else await writeFile(target, generated);
}
