// ---------------------------------------------------------------------------
// DO-NOT-EDIT banners.
//
// Eleven files under `apps/docs/content/docs/` are BOTH generated by this
// script AND tracked in Git, while their siblings are gitignored. Nothing in
// the file said so, so the first external documentation pull request against
// one of them would be silently reverted by the next `bun run lint`, which
// regenerates via `prelint`. That is the worst possible first-contributor
// experience: the change is reviewed, merged, and then quietly disappears.
//
// The banner form is chosen so it can never break a build:
//   - Markdown: a YAML COMMENT inside the frontmatter block. Not a key, so no
//     schema sees it, and it never reaches the rendered page.
//   - meta.json: a `$generated` key. fumadocs parses meta files with a
//     non-strict Zod object (`fumadocs-core/source/schema`), which strips keys
//     it does not declare.
//
// `scripts/validate/generated-docs-banner.test.ts` asserts that every tracked
// generated file carries one.
// ---------------------------------------------------------------------------

/** The marker both the banner and its gate key on. Changing it changes both. */
const GENERATED_DOC_MARKER = "GENERATED FILE - do not edit";

const GENERATOR_PATH = "scripts/docs/generate-all.mjs";

function markdownBannerLines(source) {
  return [
    `# ${GENERATED_DOC_MARKER}.`,
    source === undefined
      ? `# Written by \`${GENERATOR_PATH}\`.`
      : `# Written by \`${GENERATOR_PATH}\` from \`${source}\`.`,
    "# Edit the source and run `bun run docs:generate`. A hand edit here is",
    "# reverted by the next `bun run lint`, which regenerates via `prelint`."
  ];
}

/**
 * Inserts the banner immediately after the opening `---` of a frontmatter
 * block. Every document this script copies has one; a source without one is a
 * layout change that should fail loudly rather than silently ship an
 * unbannered file.
 */
function withMarkdownBanner(content, source) {
  if (!content.startsWith("---\n") && !content.startsWith("---\r\n")) {
    throw new Error(`docs generator: ${source ?? "generated document"} has no frontmatter block to bannerize`);
  }
  const newline = content.startsWith("---\r\n") ? "\r\n" : "\n";
  const opening = `---${newline}`;
  return opening + markdownBannerLines(source).join(newline) + newline + content.slice(opening.length);
}

/** meta.json equivalent: a leading key fumadocs' non-strict schema strips. */
function withMetaBanner(meta) {
  return {
    $generated: `${GENERATED_DOC_MARKER}. Written by ${GENERATOR_PATH}; run 'bun run docs:generate'.`,
    ...meta
  };
}

